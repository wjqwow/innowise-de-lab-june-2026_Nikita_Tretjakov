products = ["Яблоки", "Хлеб", "Молоко", "Печенье", "Сок", "Кефир"]
for i in range (0, len(products), 2):
    X = products[i]
    if X == "Бананы":
        print(f"Обнаружены бананы! Проверка экстренно прервана.")
        break 
    Y = len(X)
    print(f"Индекс {i}: Проверен товар {X} (Длина названия: {Y} символов)")
else:
    print("--- Выборочная проверка успешно завершена ---")
