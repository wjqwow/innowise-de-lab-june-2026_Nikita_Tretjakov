"""
Скрипт расчёта геометрических параметров квадратных зон хранения.

Назначение:
    Инструмент для департамента логистики, позволяющий быстро рассчитать
    длину ограждения (периметр) для новых квадратных зон хранения
    на основе известной площади зоны.

Автор: 
    Департамент логистики

Версия: 
    1.0.0

Дата создания: 
    2026-08-15

Бизнес-контекст:
    - Входные данные: идентификатор зоны (строка) и площадь в квадратных метрах (число)
    - Выходные данные: идентификатор зоны расчета,длина одной стены в метрах

"""
import math
area_total = 225
zone_name = input('Введите идентификатор зоны: ')
print(f'Расчет для объекта: {zone_name}')
side_length = math.sqrt(area_total)
print(f'Длина стены зоны: {side_length} метров')

